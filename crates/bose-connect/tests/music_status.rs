/// Run `get_music_status` against a fake device that answers the
/// request with `reply`, written in small chunks.
fn status_from(reply: &'static [u8]) -> Result<MusicStatus, BoseError> {
    let (mut client, mut device) = UnixStream::pair().unwrap();
    client
        .set_read_timeout(Some(Duration::from_millis(200)))
        .unwrap();
    let fake = thread::spawn(move || {
        let mut request = [0u8; 4];
        device.read_exact(&mut request).unwrap();
        assert_eq!(request, REQUEST);
        for chunk in reply.chunks(7) {
            device.write_all(chunk).unwrap();
        }
        // Keep the socket open until the client is done.
        let mut rest = [0u8; 1];
        let _ = device.read(&mut rest);
    });
    let result = get_music_status(&mut client);
    drop(client);
    fake.join().unwrap();
    result
}

#[test]
fn phone_source_with_metadata() {
    let status = status_from(WHITE_PHONE_PLAYING).unwrap();
    assert_eq!(status.state, PlayState::Playing);
    assert_eq!(status.position, Some(52));
    assert_eq!(status.title.as_deref(), Some("Hey, Soul Sister"));
    assert_eq!(status.artist.as_deref(), Some("Train"));
    assert_eq!(
        status.album.as_deref(),
        Some("Save Me, San Francisco (Golden Gate Edition)")
    );
}

#[test]
fn computer_without_a_media_player_tells_nothing() {
    let status = status_from(WHITE_LAPTOP_NO_PLAYER).unwrap();
    assert_eq!(status, MusicStatus::default());
}

#[test]
fn computer_with_mpris_proxy_sends_utf8_metadata() {
    let status = status_from(WHITE_LAPTOP_MPRIS_PROXY).unwrap();
    assert_eq!(status.state, PlayState::Stopped);
    assert_eq!(status.position, None);
    assert_eq!(status.title.as_deref(), Some("Vício"));
    assert_eq!(status.artist.as_deref(), Some("Lola Club"));
    assert_eq!(status.album.as_deref(), Some("Homónimo"));
}

#[test]
fn qc_ultra_skips_its_other_block_05_packets() {
    let status = status_from(ULTRA_PHONE_PLAYING).unwrap();
    assert_eq!(status.state, PlayState::Playing);
    assert_eq!(status.position, Some(31));
    assert_eq!(status.title, None);
}

#[test]
fn unknown_music_is_stopped() {
    let status = status_from(&[0x05, 0x02, 0x04, 0x01, 0x0c]).unwrap();
    assert_eq!(status, MusicStatus::default());
}

#[test]
fn another_error_is_reported() {
    let err = status_from(&[0x05, 0x02, 0x04, 0x01, 0x05]).unwrap_err();
    assert!(matches!(
        err,
        BoseError::DeviceError {
            block: 0x05,
            function: 0x02,
            code: 0x05
        }
    ));
}

#[test]
fn a_notification_from_another_block_is_skipped() {
    // A voice-prompt notification arrives before the reply.
    const REPLY: &[u8] = &[
        0x01, 0x03, 0x03, 0x05, 0xa6, 0x00, 0x04, 0xcf, 0xde, 0x05, 0x02, 0x07, 0x00, 0x05, 0x04,
        0x03, 0x03, 0x02, 0x00, 0x3c, 0x05, 0x02, 0x06, 0x00,
    ];
    let status = status_from(REPLY).unwrap();
    assert_eq!(status.state, PlayState::Paused);
    assert_eq!(status.position, Some(60));
}
